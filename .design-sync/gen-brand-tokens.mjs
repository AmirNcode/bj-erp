// Emits the app's brand colours (app/globals.css :root) as literal `--color-*` tokens so
// Claude Design's token index lists them. The app maps them through `@theme inline`, which
// leaves no literal `--color-*` variables for the indexer to find. Values only; utilities
// keep using var(--primary) etc., so rendering is unchanged.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const css = readFileSync('app/globals.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const root = /:root\s*\{([\s\S]*?)\}/.exec(css)?.[1];
if (!root) throw new Error('gen-brand-tokens: no :root block in app/globals.css');

const vars = new Map();
for (const m of root.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) vars.set(m[1], m[2].trim());
const resolve = (v, seen = new Set()) => v.replace(/var\(--([\w-]+)\)/g, (_, n) => {
  if (seen.has(n) || !vars.has(n)) throw new Error(`gen-brand-tokens: cannot resolve --${n}`);
  return resolve(vars.get(n), new Set([...seen, n]));
});

const lines = [];
for (const [name, value] of vars) {
  if (name === 'radius') lines.push(`  --radius-brand: ${resolve(value)};`);
  else if (/^(oklch|#|rgb|hsl)|var\(/.test(value)) lines.push(`  --color-${name}: ${resolve(value)};`);
}
mkdirSync('.design-sync/.cache', { recursive: true });
writeFileSync('.design-sync/.cache/brand-tokens.css',
  `/* generated by .design-sync/gen-brand-tokens.mjs from app/globals.css */\n:root {\n${lines.join('\n')}\n}\n`);
console.error(`gen-brand-tokens: ${lines.length} tokens`);
